
"""API tests using a mocked LLM."""

from fastapi.testclient import TestClient

from app.main import app
from app.llm import LLMGenerationError

import pytest

client = TestClient(app)


@pytest.fixture(autouse=True)
def isolated_database(test_db, monkeypatch):
    """Redirect API database access to temporary DuckDB."""

    monkeypatch.setattr(
        "app.database.DB_PATH",
        test_db,
    )



def test_health():
    response = client.get("/health")

    assert response.status_code == 200
    assert response.json() == {"status": "ok"}


def test_ask_with_mocked_llm(monkeypatch):
    """Test the API without calling Gemini."""

    monkeypatch.setattr(
        "app.main.generate_sql",
        lambda question: (
            "SELECT cliente, total_comprado "
            "FROM top_10_clientes "
            "ORDER BY total_comprado DESC LIMIT 10"
        ),
    )

    response = client.post(
        "/ask",
        json={
            "question": "¿Cuáles son los 10 mejores clientes?"
        },
    )

    assert response.status_code == 200

    data = response.json()

    assert data["row_count"] == 10
    assert len(data["rows"]) == 10
    assert data["rows"][0]["cliente"] == "Cliente_060"


def test_ask_rejects_unsafe_sql(monkeypatch):
    """Reject destructive SQL generated by the LLM."""

    monkeypatch.setattr(
        "app.main.generate_sql",
        lambda question: "DELETE FROM pedidos",
    )

    response = client.post(
        "/ask",
        json={"question": "Elimina todos los pedidos"},
    )

    assert response.status_code == 400
    assert "Unsafe or invalid SQL" in response.json()["detail"]


def test_ask_handles_llm_failure(monkeypatch):
    """Return a controlled error if Gemini fails."""

    def fake_llm(question):
        raise LLMGenerationError("Gemini unavailable.")

    monkeypatch.setattr(
        "app.main.generate_sql",
        fake_llm,
    )

    response = client.post(
        "/ask",
        json={"question": "¿Cuánto vendimos?"},
    )

    assert response.status_code == 503
